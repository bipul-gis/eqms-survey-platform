export const shouldSeedUddQuestionnaireForProject = (projectId?: string, projectName?: string): boolean => {
  if (!projectId || !projectName) return false;
  const haystack = `${projectId} ${projectName}`.toLowerCase();
  return /upazila|twelve|12.*upazila|socio[- ]economic|comprehensive development plan|udd|ulb|socio-economic/i.test(haystack);
};

